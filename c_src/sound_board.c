/* Power-on.  sample_rate 0 = run the board without rendering audio (the
 * probes: the register stream is the product). */
void sndboard_init(int sample_rate)
{
    audio_rate  = sample_rate;
    audio_phase = 0;
    ay8910_init(&ay[0], AY_CLOCK_HZ, sample_rate > 0 ? sample_rate : 48000);
    ay8910_init(&ay[1], AY_CLOCK_HZ, sample_rate > 0 ? sample_rate : 48000);
    snd_reset();
}

/* The main CPU's `out ($14),a`. */
void sndboard_command(uint8_t cmd)
{
    snd_irq_latch(cmd);
}

/* One GBNMI.  SND_NMI_244HZ 0x0066 bumps snd_tick, the main loop sees it
 * move and runs a pass; then the tick's worth of audio is rendered from
 * the registers as that pass left them and pushed to the backend.  The
 * two chips are summed in equal parts (MAME routes both at the same
 * gain); each chip's table tops out at a third of full scale per channel
 * (ay8910.c), so the halved sum cannot clip. */
void sndboard_tick(void)
{
    int n, i;

    wr(SND_TICK, (uint8_t)(rd(SND_TICK) + 1));      /* SND_NMI_244HZ      */
    if (rd(SND_TICK) != rd(SND_TICK_PREV)) {        /* snd_main_loop      */
        wr(SND_TICK_PREV, rd(SND_TICK));
        snd_main_pass();
    }

    if (audio_rate <= 0) return;
    {
        uint64_t acc = (uint64_t)audio_phase + (uint64_t)audio_rate * NMI_DIVIDER;
        n = (int)(acc / NMI_XTAL_HZ);
        audio_phase = (uint32_t)(acc % NMI_XTAL_HZ);
    }
    if (n > (int)(sizeof audio_buf[0] / sizeof audio_buf[0][0]))
        n = (int)(sizeof audio_buf[0] / sizeof audio_buf[0][0]);
    if (n <= 0) return;

    ay8910_render(&ay[0], audio_buf[0], n);
    ay8910_render(&ay[1], audio_buf[1], n);
    for (i = 0; i < n; i++)
        audio_buf[0][i] = (int16_t)(((int)audio_buf[0][i] + (int)audio_buf[1][i]) / 2);
    plat_audio_push(audio_buf[0], n);
}
